"""TOP-4 PLACE QUINELLA (QPL) BACKTEST, 2023 onward.

Strategy
--------
For each race, rank runners with a *walk-forward / out-of-fold* win model.
Select the top 4 runners. Buy all six QPL combinations among them:

    C(4, 2) = 6 tickets per race.

A QPL ticket wins if BOTH selected horses officially qualify for placing.
For a normal HKJC race, this normally means both finish in the top 3; however,
this script derives actual winning QPL pairs from the official `dividends.csv`
records rather than hard-coding top-3 rules. This also handles edge cases such
as dead heats and races that pay more qualifying combinations.

Critical data rule
------------------
`dividends.csv` contains only PAID / winning combinations, not a full odds
board. It is therefore valid for:
  - checking whether the six tickets won;
  - applying the official payout to tickets that won;
  - calculating realised historical ROI for this pre-specified Top-4 strategy.

It is NOT valid for:
  - computing an ex-ante market edge for losing QPL combinations;
  - claiming that a historical result proves a real-time market overlay.

Anti-leakage rule
-----------------
DO NOT use in-sample probabilities generated by a model trained on the same
race. This script requires an OUT-OF-FOLD / walk-forward prediction file.
The prediction file must cover each scored race with a prediction made without
training on that race or a future race.

Expected prediction columns:
  race_date, venue, race_no, horse_id, pred_win_prob_raw
Optional:
  pred_win_prob_platt_oof (preferred if it is genuinely OOF), fold

Before running, set PREDICTION_PATH below to your OOF/walk-forward prediction
file. Do not point it to output/full18y/F_reg_2_predictions_full18y.csv: that
file is in-sample and would make this evaluation invalid.

Run:
  python3 features/backtest_place_quinella_top4_2023.py

Outputs:
  output/place_quinella_top4_2023/place_quinella_top4_bets.csv
  output/place_quinella_top4_2023/place_quinella_top4_race_summary.csv
  output/place_quinella_top4_2023/place_quinella_top4_summary.csv
"""

from __future__ import annotations

from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd


# ---------------------------------------------------------------------------
# Configuration: change only PREDICTION_PATH if your OOF prediction filename
# differs. The script intentionally refuses the in-sample full18y file.
# ---------------------------------------------------------------------------
START_DATE = pd.Timestamp("2023-01-01")
STAKE_PER_TICKET = 10.0  # HKJC dividends are conventionally per HK$10 unit.
TOP_K = 4
POOL_NAMES = {"QUINELLA PLACE", "QPL", "PLACE QUINELLA"}

PREDICTION_PATH = Path("output/regularization/F_reg_2_predictions_all_folds.csv")
TRAIN_PATH = Path("training_set_safe.csv")
DIVIDENDS_PATH = Path("dividends.csv")
OUTPUT_DIR = Path("output/place_quinella_top4_2023")


def check_paths() -> None:
    if not PREDICTION_PATH.exists():
        raise FileNotFoundError(
            f"搵唔到 OOF prediction file: {PREDICTION_PATH}\n"
            "請將 PREDICTION_PATH 改成真正 walk-forward / OOF predictions CSV。"
        )
    if "full18y" in str(PREDICTION_PATH).lower():
        raise ValueError(
            "拒絕使用 full18y in-sample predictions 做回測。\n"
            "請使用真正 out-of-fold / walk-forward prediction file，否則會有 leakage。"
        )
    if not TRAIN_PATH.exists():
        raise FileNotFoundError(f"搵唔到 training data: {TRAIN_PATH}")
    if not DIVIDENDS_PATH.exists():
        raise FileNotFoundError(f"搵唔到 dividends data: {DIVIDENDS_PATH}")


def load_predictions_and_saddle() -> tuple[pd.DataFrame, str]:
    """Load OOF predictions and attach saddle numbers from the training set."""
    pred = pd.read_csv(PREDICTION_PATH)
    train = pd.read_csv(TRAIN_PATH)

    keys = ["race_date", "venue", "race_no", "horse_id"]
    required_pred = set(keys + ["pred_win_prob_raw"])
    required_train = set(keys + ["saddle"])

    missing_pred = sorted(required_pred - set(pred.columns))
    missing_train = sorted(required_train - set(train.columns))
    if missing_pred:
        raise ValueError(f"Prediction file 缺少欄位: {missing_pred}")
    if missing_train:
        raise ValueError(f"training_set_safe.csv 缺少欄位: {missing_train}")

    pred["race_date"] = pd.to_datetime(pred["race_date"], errors="coerce")
    train["race_date"] = pd.to_datetime(train["race_date"], errors="coerce")
    pred["race_no"] = pd.to_numeric(pred["race_no"], errors="coerce")
    train["race_no"] = pd.to_numeric(train["race_no"], errors="coerce")

    # Prefer genuinely OOF Platt probabilities if supplied; otherwise raw OOF.
    prob_col = "pred_win_prob_platt_oof" if "pred_win_prob_platt_oof" in pred.columns else "pred_win_prob_raw"
    pred[prob_col] = pd.to_numeric(pred[prob_col], errors="coerce")

    # Ensure the training key is one-to-one before merging.
    train_saddle = train[keys + ["saddle"]].drop_duplicates()
    if train_saddle.duplicated(keys).any():
        raise ValueError("training_set_safe.csv 的 (race, horse) key 唔唯一，唔可以安全 merge saddle。")

    keep = [c for c in keys + [prob_col] if c in pred.columns]
    if "fold" in pred.columns:
        keep.append("fold")
    pred = pred[keep].copy()

    if pred.duplicated(keys).any():
        n_dup = int(pred.duplicated(keys).sum())
        raise ValueError(
            f"Prediction file 有 {n_dup} 個重複 (race, horse) keys。"
            "請先確認只保留一個真正 OOF prediction per runner。"
        )

    df = pred.merge(train_saddle, on=keys, how="left", validate="one_to_one")
    df = df[df["race_date"] >= START_DATE].copy()
    missing_saddle = int(df["saddle"].isna().sum())
    if missing_saddle:
        print(f"⚠️ {missing_saddle} 個 prediction 無 saddle，已剔除。")
        df = df.dropna(subset=["saddle"])

    df["saddle"] = df["saddle"].astype(int)
    df = df.dropna(subset=[prob_col]).copy()
    return df, prob_col


def load_qpl_dividends() -> pd.DataFrame:
    """Load paid QPL combinations and parse each into a sorted saddle pair."""
    div = pd.read_csv(DIVIDENDS_PATH)
    required = {"race_date", "venue", "race_no", "pool", "combination", "dividend"}
    missing = sorted(required - set(div.columns))
    if missing:
        raise ValueError(f"dividends.csv 缺少欄位: {missing}")

    div["race_date"] = pd.to_datetime(div["race_date"], errors="coerce")
    div["race_no"] = pd.to_numeric(div["race_no"], errors="coerce")
    div["dividend"] = pd.to_numeric(div["dividend"], errors="coerce")
    div["pool_norm"] = div["pool"].astype(str).str.upper().str.strip()
    div = div[(div["race_date"] >= START_DATE) & div["pool_norm"].isin(POOL_NAMES)].copy()

    def parse_pair(value: object) -> tuple[int, int] | None:
        parts = str(value).replace(" ", "").split(",")
        if len(parts) != 2:
            return None
        try:
            a, b = int(parts[0]), int(parts[1])
        except ValueError:
            return None
        return tuple(sorted((a, b)))

    div["saddle_pair"] = div["combination"].map(parse_pair)
    div = div.dropna(subset=["saddle_pair", "dividend"])
    keys = ["race_date", "venue", "race_no", "saddle_pair"]
    if div.duplicated(keys).any():
        # For a genuinely duplicated payout record use the last record only;
        # log it since this should be rare and needs audit visibility.
        print(f"⚠️ QPL 派彩表有 {int(div.duplicated(keys).sum())} 重複組合，保留最後一行。")
        div = div.drop_duplicates(keys, keep="last")

    return div[["race_date", "venue", "race_no", "saddle_pair", "dividend"]].copy()


def build_top4_tickets(pred: pd.DataFrame, prob_col: str) -> pd.DataFrame:
    """Rank each race, select exactly Top-4 and generate its 6 QPL tickets."""
    race_keys = ["race_date", "venue", "race_no"]
    tickets: list[dict] = []
    skipped_short_fields = 0

    for race_key, race in pred.groupby(race_keys, sort=True):
        race = race.sort_values([prob_col, "saddle"], ascending=[False, True]).copy()
        if len(race) < TOP_K:
            skipped_short_fields += 1
            continue

        selected = race.head(TOP_K)
        selected_rows = selected[["horse_id", "saddle", prob_col]].to_dict("records")
        selected_horse_ids = tuple(selected["horse_id"].tolist())
        selected_saddles = tuple(selected["saddle"].astype(int).tolist())

        for a, b in combinations(selected_rows, 2):
            tickets.append({
                "race_date": race_key[0],
                "venue": race_key[1],
                "race_no": race_key[2],
                "horse_i": a["horse_id"],
                "horse_j": b["horse_id"],
                "saddle_i": int(a["saddle"]),
                "saddle_j": int(b["saddle"]),
                "saddle_pair": tuple(sorted((int(a["saddle"]), int(b["saddle"])))),
                "prob_i": float(a[prob_col]),
                "prob_j": float(b[prob_col]),
                "top4_horse_ids": "|".join(selected_horse_ids),
                "top4_saddles": "|".join(map(str, selected_saddles)),
                "rank_i": int(selected.index.get_loc(a["horse_id"])) + 1 if False else np.nan,
            })

    if skipped_short_fields:
        print(f"⚠️ 跳過 {skipped_short_fields} 場少於 {TOP_K} 匹馬的場次。")

    return pd.DataFrame(tickets)


def main() -> None:
    check_paths()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    print(f"📂 Loading OOF predictions: {PREDICTION_PATH}")
    pred, prob_col = load_predictions_and_saddle()
    print(f"✅ 使用 probability 欄位: {prob_col}")
    print(f"📊 Predictions from {pred['race_date'].min().date()} to {pred['race_date'].max().date()}")
    print(f"📊 Prediction races from 2023 onward: {pred.groupby(['race_date','venue','race_no']).ngroups}")

    print("📂 Loading official QPL dividends...")
    qpl = load_qpl_dividends()
    print(f"📊 QPL paid-combination rows from 2023 onward: {len(qpl)}")
    print(f"📊 Races with QPL records from 2023 onward: {qpl.groupby(['race_date','venue','race_no']).ngroups}")

    print(f"\n🎯 Selecting top {TOP_K} horses, then buying all {TOP_K * (TOP_K - 1) // 2} QPL combinations...")
    tickets = build_top4_tickets(pred, prob_col)
    if tickets.empty:
        raise RuntimeError("冇生成到任何 tickets。請檢查 prediction coverage。")

    race_keys = ["race_date", "venue", "race_no"]
    tickets = tickets.merge(qpl, on=race_keys + ["saddle_pair"], how="left", validate="many_to_one")
    tickets["is_winner"] = tickets["dividend"].notna()
    tickets["stake"] = STAKE_PER_TICKET
    tickets["return"] = np.where(tickets["is_winner"], tickets["dividend"], 0.0)
    tickets["net_profit"] = tickets["return"] - tickets["stake"]

    # One race is actionable only when it has official QPL dividend records.
    race_has_qpl = qpl[race_keys].drop_duplicates()
    ticket_races = tickets[race_keys].drop_duplicates()
    coverage = ticket_races.merge(race_has_qpl, on=race_keys, how="left", indicator=True)
    eligible_races = coverage[coverage["_merge"] == "both"][race_keys]
    tickets = tickets.merge(eligible_races, on=race_keys, how="inner", validate="many_to_one")

    # Race-level performance: exactly 6 tickets per eligible race.
    race_summary = tickets.groupby(race_keys, as_index=False).agg(
        n_tickets=("stake", "size"),
        n_winning_tickets=("is_winner", "sum"),
        stake=("stake", "sum"),
        total_return=("return", "sum"),
        net_profit=("net_profit", "sum"),
        selected_top4=("top4_saddles", "first"),
    )
    race_summary["roi"] = race_summary["net_profit"] / race_summary["stake"]

    total_stake = float(tickets["stake"].sum())
    total_return = float(tickets["return"].sum())
    total_profit = total_return - total_stake
    overall_roi = total_profit / total_stake if total_stake else np.nan
    n_races = len(race_summary)
    n_tickets = len(tickets)
    n_wins = int(tickets["is_winner"].sum())
    n_races_with_win = int((race_summary["n_winning_tickets"] > 0).sum())

    summary = pd.DataFrame([{
        "start_date": START_DATE.date().isoformat(),
        "prediction_probability_column": prob_col,
        "strategy": f"top_{TOP_K}_horses__all_{TOP_K * (TOP_K - 1) // 2}_QPL_pairs",
        "stake_per_ticket_hkd": STAKE_PER_TICKET,
        "eligible_races": n_races,
        "tickets": n_tickets,
        "winning_tickets": n_wins,
        "ticket_hit_rate": n_wins / n_tickets if n_tickets else np.nan,
        "races_with_at_least_one_winning_ticket": n_races_with_win,
        "race_hit_rate": n_races_with_win / n_races if n_races else np.nan,
        "total_stake_hkd": total_stake,
        "total_return_hkd": total_return,
        "net_profit_hkd": total_profit,
        "roi": overall_roi,
    }])

    # Monthly figures reveal whether the result is consistent or a few-meeting fluke.
    tickets["month"] = tickets["race_date"].dt.to_period("M").astype(str)
    monthly = tickets.groupby("month", as_index=False).agg(
        races=("race_no", "nunique"),
        tickets=("stake", "size"),
        wins=("is_winner", "sum"),
        stake=("stake", "sum"),
        total_return=("return", "sum"),
        net_profit=("net_profit", "sum"),
    )
    monthly["roi"] = monthly["net_profit"] / monthly["stake"]

    tickets.to_csv(OUTPUT_DIR / "place_quinella_top4_bets.csv", index=False)
    race_summary.to_csv(OUTPUT_DIR / "place_quinella_top4_race_summary.csv", index=False)
    summary.to_csv(OUTPUT_DIR / "place_quinella_top4_summary.csv", index=False)
    monthly.to_csv(OUTPUT_DIR / "place_quinella_top4_monthly.csv", index=False)

    print("\n" + "=" * 84)
    print(f"🏁 TOP-{TOP_K} PLACE QUINELLA BACKTEST — {START_DATE.date()} onward")
    print("=" * 84)
    print(f"Eligible races with QPL dividends: {n_races}")
    print(f"Strategy: Select top {TOP_K}; buy all {TOP_K * (TOP_K - 1) // 2} QPL pairs per race")
    print(f"Tickets: {n_tickets:,}; winning tickets: {n_wins:,}; ticket hit rate: {n_wins / n_tickets:.2%}")
    print(f"Races with >=1 winning QPL ticket: {n_races_with_win:,}/{n_races:,} ({n_races_with_win / n_races:.2%})")
    print(f"Stake: HK${total_stake:,.1f}")
    print(f"Return: HK${total_return:,.1f}")
    print(f"Net profit: HK${total_profit:,.1f}")
    print(f"ROI: {overall_roi:+.2%}")

    print("\n⚠️ Interpretation guardrail:")
    print("This is a valid outcome check for a PRE-SPECIFIED Top-4 selection rule only if")
    print("the prediction file is genuinely OOF/walk-forward. It uses official payouts for")
    print("winning QPL pairs, but does NOT test ex-ante value versus a full historical odds board.")
    print("Do not claim an executable market edge without complete pre-race QPL odds.")

    print("\n✅ Saved:")
    print(f" - {OUTPUT_DIR / 'place_quinella_top4_bets.csv'}")
    print(f" - {OUTPUT_DIR / 'place_quinella_top4_race_summary.csv'}")
    print(f" - {OUTPUT_DIR / 'place_quinella_top4_summary.csv'}")
    print(f" - {OUTPUT_DIR / 'place_quinella_top4_monthly.csv'}")


if __name__ == "__main__":
    main()